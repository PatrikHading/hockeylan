ALTER TABLE loans
    ALTER COLUMN expected_return_date
        DROP NOT NULL;

CREATE TABLE borrower_aliases
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    alias_name    VARCHAR(100)                NOT NULL,
    borrower_name VARCHAR(100)                NOT NULL,
    email         VARCHAR(150)                NOT NULL,
    phone_number  VARCHAR(30)                 NOT NULL,
    version       BIGINT                      NOT NULL DEFAULT 0,
    created_date  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_date  TIMESTAMP WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT borrower_aliases_pkey
        PRIMARY KEY (id),

    CONSTRAINT chk_borrower_aliases_alias_name_not_blank
        CHECK (length(trim(alias_name)) > 0),

    CONSTRAINT chk_borrower_aliases_borrower_name_not_blank
        CHECK (length(trim(borrower_name)) > 0),

    CONSTRAINT chk_borrower_aliases_email_not_blank
        CHECK (length(trim(email)) > 0),

    CONSTRAINT chk_borrower_aliases_phone_number_not_blank
        CHECK (length(trim(phone_number)) > 0)
);

CREATE UNIQUE INDEX ux_borrower_aliases_alias_name_lower
    ON borrower_aliases (lower(alias_name));